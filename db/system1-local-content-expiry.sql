--  ⚠️ آمنة تماماً: إضافة عمود نصّيّ قابل للإفراغ (nullable) — لا تُعدّل صفّاً
--     قائماً ولا تكسر أي استعلام. والكود يعمل قبلها وبعدها (يسقط بهدوء عند
--     غيابها: register.html OPTIONAL_COLS · loadSupDocs · doc-renew fetchReg).
