ALTER TABLE proc_supplier_registrations
  ADD COLUMN IF NOT EXISTS local_content_expiry TEXT;

COMMENT ON COLUMN proc_supplier_registrations.local_content_expiry IS
  'تاريخ انتهاء شهادة المحتوى المحلي (YYYY-MM-DD) — يغذّي لوحة المتابعة وبريد التجديد';

-- تحقّق: يجب أن يعيد صفّاً واحداً
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_name = 'proc_supplier_registrations'
  AND column_name = 'local_content_expiry';
