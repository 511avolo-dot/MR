ALTER TABLE proc_users ADD COLUMN IF NOT EXISTS mobile TEXT;
COMMENT ON COLUMN proc_users.mobile IS 'جوّال الموظّف — يُدخِله بنفسه عند التسجيل الذاتيّ';

-- مفتاح إبطال الروابط: أي رمز صدر قبل `epoch` يسقط. يُنشَأ فارغاً (لا إبطال).
-- ⚠️ `proc_config_guard` يحرس الإعدادات، فنرفع هوية الخدمة محصورةً بالمعاملة.
SELECT set_config('request.jwt.claims', '{"role":"service_role"}', true);
INSERT INTO proc_settings (key, value)
VALUES ('staff_invite', '{"epoch":0}'::jsonb)
ON CONFLICT (key) DO NOTHING;
SELECT set_config('request.jwt.claims', '', true);

