--  طلب المالك: «رابط لدعوة موظفين ومدير الصيانة والتشغيل للدخول وتسجيل بياناتهم
--  لتوصلهم الإشعارات والمتابعة». الرمز موقَّع HMAC ويحمل حمولته، فلا جدول رموز
--  ولا هجرة له — هذه الهجرة تضيف حقلاً واحداً ومفتاح إبطال.
--  ⚠️ الحساب يُنشأ **موقوفاً** بقطاعٍ من الرمز؛ التفعيل بيد المالك من اللوحة.
