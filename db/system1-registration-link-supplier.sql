ALTER TABLE proc_supplier_registrations
  ADD COLUMN IF NOT EXISTS link_supplier_id TEXT;

COMMENT ON COLUMN proc_supplier_registrations.link_supplier_id IS
  'معرّف بطاقة المورد في proc_suppliers التي جاء منها رابط الدعوة — يُكمَّل عليها عند الاعتماد بدل إنشاء بطاقة جديدة.';

CREATE INDEX IF NOT EXISTS idx_reg_link_supplier
  ON proc_supplier_registrations (link_supplier_id)
  WHERE link_supplier_id IS NOT NULL;
